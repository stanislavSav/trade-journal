// A trade is «угода» (feminine).
const newTrades = pluralUk({
  one: (n) => `${n} нова`,
  few: (n) => `${n} нові`,
  many: (n) => `${n} нових`,
  other: (n) => `${n} нової`,
})
const updatedTrades = pluralUk({
  one: (n) => `${n} оновлена`,
  few: (n) => `${n} оновлені`,
  many: (n) => `${n} оновлених`,
  other: (n) => `${n} оновленої`,
})

// A bag is «позиція» (feminine), a trade is «угода» (feminine). A no-break space keeps the number with its word.
